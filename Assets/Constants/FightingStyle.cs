namespace Enums
{
    public enum FightingStyle : short
    {
        Balanced,       // Fights with a balanced mixture of moves and styles.
        Melee,       // Primarily uses hand-to-hand and melee combat. Values strength, speed, melee.
        Psychic,       // Primarily uses mental jutsus to attack or manipulate opponents. Values psychic, and spellcraft slightly.
        Spellslinger,       // Uses ranged jutsus to attack or manipulate their opponents. 
        Medical         // Primarily focuses on healing.
    }
}